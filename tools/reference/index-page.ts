/** Builds `docs/reference/copies/index.md` and the module lists it links to. */
import { readdir, stat } from "node:fs/promises";
import { join, relative } from "node:path";

import { Schema } from "effect";

import { COPIES, type ApiPointer, type Manifest, type Source } from "./manifest.ts";
import { apiPath, pinnedVersion, type Pins } from "./pins.ts";

/** What `versions.json` records for one source. `commits` follow the order of its Git origins. */
const SourceRecord = Schema.Struct({
  version: Schema.String,
  fingerprint: Schema.String,
  commits: Schema.Array(Schema.String),
});

type SourceRecord = typeof SourceRecord.Type;

const Records = Schema.Record(Schema.String, SourceRecord);

export type Records = typeof Records.Type;

export const decodeRecords = Schema.decodeUnknownSync(Records);

/** Generated file paths, relative to the copies folder, with their contents. */
export type Generated = ReadonlyMap<string, string>;

/** Everything the index is built from. `copies` holds the copied docs. */
export interface IndexInput {
  readonly cwd: string;
  readonly copies: string;
  readonly manifest: Manifest;
  readonly pins: Pins;
  readonly records: Records;
}

const API_INDEX = "api-index";
const SKIPPED_FOLDERS = new Set(["internal", "node_modules", "dist"]);
const MODULE_FILE = /\.(d\.)?ts$/u;
const MAX_SUMMARY = 160;

const HEADER = [
  "# Reference index",
  "",
  "Generated by `mise run docs`; do not edit. Read a dependency's entry before writing or planning code against it, and use only APIs found there.",
  "",
  "Docs are copies matched to the pinned version. API files are installed by the package and are read in place.",
];

const copiesPath = (name: string, version: string): string => `${COPIES}/${name}/${version}`;

/** The first sentence of the doc comment that opens a file. */
const summaryOf = (text: string): string => {
  const match = /^(?:\s*\/\/\/.*\n)*\s*\/\*\*([\s\S]*?)\*\//u.exec(text);
  if (match?.[1] === undefined) return "";

  const lines = match[1]
    .trim()
    .split("\n")
    .map((line) => line.replace(/^\s*\*?\s?/u, "").trim());

  const end = lines.findIndex((line) => line === "" || line.startsWith("@"));
  const paragraph = (end === -1 ? lines : lines.slice(0, end)).join(" ");
  const sentence = /^.*?[.!?](?=\s|$)/u.exec(paragraph)?.[0] ?? paragraph;

  return sentence.slice(0, MAX_SUMMARY);
};

const moduleFiles = async (root: string): Promise<string[]> => {
  const found: string[] = [];

  for (const entry of await readdir(root, { recursive: true, withFileTypes: true })) {
    const folder = relative(root, entry.parentPath);
    const skipped = folder.split("/").some((part) => SKIPPED_FOLDERS.has(part));

    if (entry.isFile() && MODULE_FILE.test(entry.name) && !skipped)
      found.push(join(folder, entry.name));
  }

  return found.toSorted();
};

const modulePage = async (root: string, title: string): Promise<string> => {
  const entries = await Promise.all(
    (await moduleFiles(root)).map(async (file) => {
      const summary = summaryOf(await Bun.file(join(root, file)).text());
      const name = file.replace(MODULE_FILE, "");

      return summary === "" ? `- \`${name}\`` : `- \`${name}\`: ${summary}`;
    }),
  );

  return `${[`# ${title}`, "", ...entries].join("\n")}\n`;
};

const pointerName = (source: Source, pointer: ApiPointer): string =>
  [pointer.package ?? source.package, pointer.path].filter((part) => part !== "").join("/");

const docsLine = async (copies: string, source: Source, version: string): Promise<string> => {
  const root = join(copies, source.package, version);
  const entries = await readdir(root, { withFileTypes: true });

  const names = entries.flatMap((entry) => {
    if (entry.name === API_INDEX) return [];

    return [entry.isDirectory() ? `${entry.name}/` : entry.name];
  });

  const all = await Array.fromAsync(new Bun.Glob("**/*").scan({ cwd: root, onlyFiles: true }));
  const files = all.filter((file) => !file.startsWith(`${API_INDEX}/`)).length;
  const noun = files === 1 ? "file" : "files";

  return `- Docs: \`${copiesPath(source.package, version)}/\` (${files} ${noun}: ${names.join(", ")})`;
};

const originLines = (source: Source, version: string, record: SourceRecord): string[] => {
  const gitSets = source.docs.flatMap((set) => (set.origin.kind === "git" ? [set.origin] : []));

  return gitSets.map((origin, index) => {
    const ref =
      "tag" in origin.ref
        ? `tag ${origin.ref.tag.replaceAll("{version}", version)}`
        : `branch ${origin.ref.branch}`;

    const note = "branch" in origin.ref ? " (not pinned to the installed version)" : "";
    const commit = record.commits[index]?.slice(0, 12) ?? "unknown";

    return `- From: ${origin.repository}, ${ref}, commit ${commit}${note}`;
  });
};

const apiLines = async (
  input: IndexInput,
  source: Source,
  version: string,
  generated: Map<string, string>,
): Promise<string[]> =>
  Promise.all(
    source.api.map(async (pointer) => {
      const path = apiPath(input.cwd, input.pins, source, pointer);
      const location = relative(input.cwd, path);
      if (!(await stat(path)).isDirectory()) return `- API (${pointer.kind}): \`${location}\``;

      const name = pointerName(source, pointer);
      const page = `${source.package}/${version}/${API_INDEX}/${name.replaceAll("/", "-")}.md`;
      generated.set(page, await modulePage(path, name));

      return `- API (${pointer.kind}): \`${location}/\`, modules: \`${COPIES}/${page}\``;
    }),
  );

/** Builds `index.md` and the module pages it links to. API folders are read in place. */
export const buildIndex = async (input: IndexInput): Promise<Generated> => {
  const generated = new Map<string, string>();

  const sections = await Promise.all(
    input.manifest.sources.map(async (source) => {
      const version = pinnedVersion(source, input.pins);
      const record = input.records[source.package];
      if (version === undefined || record === undefined) return [];

      return [
        "",
        `## ${source.package} ${version}`,
        "",
        source.summary,
        "",
        await docsLine(input.copies, source, version),
        ...originLines(source, version, record),
        ...(await apiLines(input, source, version, generated)),
      ];
    }),
  );

  generated.set("index.md", `${[...HEADER, ...sections.flat()].join("\n")}\n`);

  return generated;
};
